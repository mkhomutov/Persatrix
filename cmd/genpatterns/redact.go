// redactSample is one input the parity test runs through both redactors.
// pattern names the Go pattern it exercises, or is empty for an input
// nothing should change.
//
// Each input is split into parts at its token prefix, and the parts are
// written to Python joined with `+`, so no whole token shape appears in
// either source: GitHub's push-time secret scanner flags those even as test
// data (the same split as internal/security/redactor_test.go).
type redactSample struct {
	pattern string
	parts   []string
}

