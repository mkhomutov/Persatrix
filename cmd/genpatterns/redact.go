// renderRedactPatterns serialises the secret redactor's table to a Python
// module body, deterministically, with each name and expression copied
// verbatim.
func renderRedactPatterns(patterns []security.RedactPattern) string {
	var b strings.Builder
	b.WriteString("# Code generated by cmd/genpatterns. DO NOT EDIT.\n")
	b.WriteString("#\n")
	b.WriteString("# Source: internal/security/redactor.go (defaultPatterns, exported as\n")
	b.WriteString("# security.DefaultRedactPatterns). Regenerate via:\n")
	b.WriteString("# make generate-sanitizer-patterns\n")
	b.WriteString("#\n")
	b.WriteString("# tests/unit/python/test_secret_redactor.py runs the Python redactor over\n")
	b.WriteString("# samples and compares the result with what Go's redactor returned for them.\n")
	b.WriteString("\n")
	b.WriteString("from __future__ import annotations\n")
	b.WriteString("\n")
	b.WriteString("#: (marker name, regular expression), in the order Go's SecretRedactor\n")
	b.WriteString("#: applies them. A match becomes ``[REDACTED:<marker name>]``.\n")
	b.WriteString("REDACT_PATTERNS: tuple[tuple[str, str], ...] = (\n")
	for _, p := range patterns {
		b.WriteString(pyLine(fmt.Sprintf("    (%s, %s),", pyRepr(p.Name), pyRepr(p.Expr))))
	}
	b.WriteString(")\n")
	return b.String()
}

// renderRedactSamples runs each sample through r and serialises the input,
// split as written, beside r's output, deterministically.
func renderRedactSamples(r *security.SecretRedactor, samples []redactSample) string {
	var b strings.Builder
	b.WriteString("# Code generated by cmd/genpatterns. DO NOT EDIT.\n")
	b.WriteString("#\n")
	b.WriteString("# Source: cmd/genpatterns/redact.go (redactSamples), each run through Go's\n")
	b.WriteString("# security.NewSecretRedactor. Regenerate via:\n")
	b.WriteString("# make generate-sanitizer-patterns\n")
	b.WriteString("#\n")
	b.WriteString("# Inputs are split at their token prefix: GitHub's push-time secret scanner\n")
	b.WriteString("# flags a whole token shape even as test data.\n")
	b.WriteString("\n")
	b.WriteString("from __future__ import annotations\n")
	b.WriteString("\n")
	b.WriteString("#: (the pattern the sample exercises, or \"\" for none; the input; what Go's\n")
	b.WriteString("#: SecretRedactor returned for it)\n")
	b.WriteString("SAMPLES: tuple[tuple[str, str, str], ...] = (\n")
	for _, s := range samples {
		parts := make([]string, len(s.parts))
		for i, p := range s.parts {
			parts[i] = pyRepr(p)
		}
		b.WriteString("    (\n")
		b.WriteString(pyLine("        " + pyRepr(s.pattern) + ","))
		b.WriteString(pyLine("        " + strings.Join(parts, " + ") + ","))
		b.WriteString(pyLine("        " + pyRepr(r.Redact(strings.Join(s.parts, ""))) + ","))
		b.WriteString("    ),\n")
	}
	b.WriteString(")\n")
	return b.String()
}

// pyLine ends a generated line, marking one over ruff's 100-character limit
// as exempt: a generated string is not split.
func pyLine(line string) string {
	if len(line) > 100 {
		return line + "  # noqa: E501\n"
	}
	return line + "\n"
}
