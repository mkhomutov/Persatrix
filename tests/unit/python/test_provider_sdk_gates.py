"""Hold the optional provider SDKs inside the gates the other dependencies pass.

``google-genai`` and ``ibm-watsonx-ai`` come with the ``providers`` extra,
which no CI job installed. So they were pinned nowhere, type-checked nowhere,
and their adapters met only stand-in modules (ISSUE-0220). These tests keep
the parts that changed that:

- a second constraints file, compiled like the first plus the extra, whose
  pins agree with the first wherever the two share a package;
- the three constraints targets cover both files;
- the required Python job installs the extra from that file, after every
  check of the plain install has run, then type-checks the two adapters
  against the real SDKs, runs their boundary tests with skipping turned into
  failing, and checks the licenses of everything the SDKs brought in;
- the weekly refresh moves, tries and commits both files.
"""

from __future__ import annotations

import configparser
import re
import shlex
import socket
import subprocess
import tomllib
from pathlib import Path
from typing import Any

import pytest
import yaml
from _test_infra import REPO_ROOT, ci_job_steps
from packaging.requirements import Requirement
from packaging.utils import canonicalize_name

from ._sdk_boundary_helpers import REQUIRE_PROVIDER_SDKS_ENV, provider_sdk, refuse_network

GITHUB = REPO_ROOT / ".github"
BASE = GITHUB / "python-constraints.txt"
PROVIDERS = GITHUB / "python-constraints-providers.txt"
BASE_ARG = ".github/python-constraints.txt"
PROVIDERS_ARG = ".github/python-constraints-providers.txt"
ADAPTERS = ("llm_gemini.py", "llm_watsonx.py")
# What `make test-providers` runs: every test that needs a real provider SDK.
# The third is one test of a file whose other tests need none.
SDK_TESTS = (
    "tests/unit/python/test_llm_sdk_boundary_gemini.py",
    "tests/unit/python/test_llm_sdk_boundary_watsonx.py",
    "tests/unit/python/test_tool_arg_check.py"
    "::TestNarrowing::test_every_keyword_passes_gemini_schema_validation",
)
# The targets that need the SDKs installed, in the order they run. The last
# is the plain install's license check under a name of its own: it reads
# whatever is installed, so here it reads the SDKs and what they pulled in,
# and a failure line says which of the two runs failed.
PROVIDER_TARGETS = (
    "build-agents-providers",
    "lint-providers",
    "test-providers",
    "check-licenses-providers",
)

# A pin line with its marker, as uv writes it: `name==1.2.3 ; marker`.
PIN_LINE_RE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._-]*==\S+(?: ;.*)?$", re.M)


def _dry_run(*args: str) -> str:
    """What `make` would run for a target, with nothing run."""
    done = subprocess.run(
        ["make", "-n", "PYTHON=python", *args],
        cwd=REPO_ROOT,
        capture_output=True,
        text=True,
        check=True,
    )
    return done.stdout


def _compiles(target: str) -> list[str]:
    """The `uv pip compile` commands a constraints target runs, one string each."""
    joined = _dry_run(target).replace("\\\n", " ")
    return [" ".join(line.split()) for line in joined.splitlines() if "pip compile" in line]


def _pin_lines(path: Path) -> set[str]:
    return set(PIN_LINE_RE.findall(path.read_text(encoding="utf-8")))


def _project() -> dict[str, Any]:
    text = (REPO_ROOT / "agents" / "pyproject.toml").read_text(encoding="utf-8")
    project: dict[str, Any] = tomllib.loads(text)["project"]
    return project


@pytest.mark.parametrize(
    ("target", "extra_flag"),
    [("python-constraints", ""), ("python-constraints-upgrade", " --upgrade")],
)
def test_both_files_are_written_by_one_command_the_second_with_the_extra(
    target: str, extra_flag: str
) -> None:
    first, second = _compiles(target)
    assert first.endswith(f"{extra_flag} -o {BASE_ARG}"), first
    assert second.endswith(f"{extra_flag} -o {PROVIDERS_ARG}"), second
    shared = first.removesuffix(f"{extra_flag} -o {BASE_ARG}")
    # The same uv, the same flags, the same environment scrubbing: the second
    # command is the first one with two things added. `-c` holds every
    # package the two files share to the first file's version.
    assert second == f"{shared} --extra providers -c {BASE_ARG}{extra_flag} -o {PROVIDERS_ARG}"
    assert " --extra providers" not in first


def test_the_check_compares_both_files() -> None:
    script = _dry_run("python-constraints-check")
    for path in (BASE_ARG, PROVIDERS_ARG):
        assert f"diff -u {path} " in script, f"python-constraints-check does not compare {path}"
    assert script.count("pip compile") == 2
    assert f"--extra providers -c {BASE_ARG}" in " ".join(script.split())


def test_the_providers_file_names_the_command_that_writes_it() -> None:
    header = PROVIDERS.read_text(encoding="utf-8").splitlines()[:2]
    assert header[0].startswith("# This file was autogenerated by uv"), header
    assert header[1].strip() == "#    make python-constraints", header


def test_every_pin_the_two_files_share_is_the_same_line() -> None:
    """The offline half of the check: the providers install differs from the
    plain one by the SDKs and what only they need, never by a shared version."""
    missing = sorted(_pin_lines(BASE) - _pin_lines(PROVIDERS))
    assert not missing, f"run `make python-constraints`; pins not carried over: {missing}"


def test_the_providers_file_pins_every_provider_sdk_inside_its_range() -> None:
    extras = _project()["optional-dependencies"]
    bundle = [Requirement(spec) for spec in extras["providers"]]
    assert len(bundle) == 1 and bundle[0].extras, "`providers` should re-export the SDK extras"
    pins: dict[str, list[str]] = {}
    for line in _pin_lines(PROVIDERS):
        name, version = line.split(" ;")[0].split("==")
        pins.setdefault(canonicalize_name(name), []).append(version)
    checked = 0
    for extra in sorted(bundle[0].extras):
        for spec in extras[extra]:
            req = Requirement(spec)
            versions = pins.get(canonicalize_name(req.name))
            assert versions, f"{req.name} (extra `{extra}`) is not pinned in {PROVIDERS_ARG}"
            outside = [v for v in versions if not req.specifier.contains(v, prereleases=True)]
            assert not outside, f"{req.name} is pinned at {outside}, outside '{req.specifier}'"
            assert canonicalize_name(req.name) not in {
                canonicalize_name(line.split("==")[0]) for line in _pin_lines(BASE)
            }, f"{req.name} is in the plain file: CI's plain install would no longer lack it"
            checked += 1
    assert checked >= 2


def test_build_agents_providers_installs_both_extras_at_the_providers_pins() -> None:
    lines = [ln.strip() for ln in _dry_run("build-agents-providers").splitlines() if "pip" in ln]
    assert lines == [f'python -m pip install -c {PROVIDERS_ARG} -e "./agents[dev,providers]"']


def test_test_providers_turns_a_skip_into_a_failure() -> None:
    (command,) = [ln.strip() for ln in _dry_run("test-providers").splitlines() if "pytest" in ln]
    # The whole command: the variable, every test that needs an SDK, and no
    # option that could deselect one.
    assert command == (
        f"{REQUIRE_PROVIDER_SDKS_ENV}=1 python -m pytest {' '.join(SDK_TESTS)} -v --tb=short"
    )
    for test in SDK_TESTS:
        assert (REPO_ROOT / test.split("::")[0]).is_file()


def test_every_test_that_needs_a_provider_sdk_runs_under_test_providers() -> None:
    """A test that needs a real SDK skips in every other run, so one that
    `make test-providers` does not name runs nowhere. That was true of a
    third test, which asked for the SDK with `importorskip`."""
    named = {test.split("::")[0] for test in SDK_TESTS}
    tests_dir = REPO_ROOT / "tests" / "unit" / "python"
    this_file = Path(__file__).name
    for path in sorted(tests_dir.glob("test_*.py")):
        if path.name == this_file:
            continue
        source = path.read_text(encoding="utf-8")
        rel = path.relative_to(REPO_ROOT).as_posix()
        # A call of the helper, not a test whose name ends the same way.
        if re.search(r"(?<![\w.])provider_sdk\(", source):
            assert rel in named, f"{rel} needs a provider SDK and `make test-providers` skips it"
        skipping = re.findall(r"importorskip\(\s*[\"'](google\.genai|ibm_watsonx_ai)", source)
        assert not skipping, f"{rel} skips without the SDK in every run: use provider_sdk()"


def _connect_a_socket() -> None:
    with socket.socket() as sock:
        sock.connect(("192.0.2.1", 443))


def test_the_network_guard_refuses_a_lookup_and_a_connection(
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    """The SDK tests rest on this guard; nothing else showed that it fires."""
    attempts = refuse_network(monkeypatch)
    tries = {
        "a name lookup": lambda: socket.getaddrinfo("example.invalid", 443),
        "create_connection": lambda: socket.create_connection(("192.0.2.1", 443), timeout=1),
        "connect": _connect_a_socket,
    }
    for what, attempt in tries.items():
        with pytest.raises(AssertionError, match="network"):
            attempt()
        assert len(attempts) == list(tries).index(what) + 1, f"{what} was not recorded"
    # An SDK that catches the error still leaves the record the tests check.
    try:
        socket.getaddrinfo("example.invalid", 443)
    except Exception:
        pass
    assert len(attempts) == len(tries) + 1


def _missing_sdk_outcome() -> str:
    """What `provider_sdk` does about an SDK that is not installed.

    Both outcomes are caught here: a skip that escaped would mark the calling
    test skipped, and it would then pass every mutation of the helper.
    """
    try:
        provider_sdk("persatrix_no_such_provider_sdk")
    except pytest.skip.Exception:
        return "skip"
    except pytest.fail.Exception as failure:
        return f"fail: {failure.msg}"
    return "imported"


def test_a_missing_sdk_is_a_failure_only_where_the_run_requires_it(
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    """What the variable above does: everywhere else a missing SDK is a skip."""
    monkeypatch.delenv(REQUIRE_PROVIDER_SDKS_ENV, raising=False)
    assert _missing_sdk_outcome() == "skip"
    monkeypatch.setenv(REQUIRE_PROVIDER_SDKS_ENV, "0")
    assert _missing_sdk_outcome() == "skip"
    monkeypatch.setenv(REQUIRE_PROVIDER_SDKS_ENV, "1")
    outcome = _missing_sdk_outcome()
    assert outcome.startswith("fail: "), outcome
    assert "make build-agents-providers" in outcome


def test_lint_providers_checks_both_adapters_with_no_config_to_excuse_a_missing_sdk() -> None:
    (command,) = [ln.strip() for ln in _dry_run("lint-providers").splitlines() if "mypy" in ln]
    # With no config, the package's settings are given as flags. A setting
    # added to [tool.mypy] has to be mirrored here, so the set is held.
    text = (REPO_ROOT / "agents" / "pyproject.toml").read_text(encoding="utf-8")
    settings = {k: v for k, v in tomllib.loads(text)["tool"]["mypy"].items() if k != "overrides"}
    assert settings == {
        "python_version": "3.11",
        "warn_return_any": True,
        "warn_unused_configs": True,
    }
    # The whole command. An empty --config-file reads no config, so the
    # sections that excuse a missing SDK for the plain install do not apply.
    # Nothing else may be added: `--ignore-missing-imports` or
    # `--follow-imports=skip` would hide the SDK again and pass.
    assert command == (
        "cd agents && python -m mypy --config-file= "
        f"--python-version {settings['python_version']} --warn-return-any {' '.join(ADAPTERS)}"
    )
    for adapter in ADAPTERS:
        assert (REPO_ROOT / "agents" / adapter).is_file()


def test_the_provider_license_check_is_the_plain_one_under_its_own_name() -> None:
    def license_commands(target: str) -> list[str]:
        return [ln.strip() for ln in _dry_run(target).splitlines() if "python_licenses.py" in ln]

    plain = license_commands("check-licenses-python")
    assert len(plain) == 1
    assert license_commands("check-licenses-providers") == plain


def test_the_adapters_import_their_sdks_without_a_type_ignore() -> None:
    for adapter, package in zip(ADAPTERS, ("google.genai", "ibm_watsonx_ai"), strict=True):
        source = (REPO_ROOT / "agents" / adapter).read_text(encoding="utf-8")
        imports = [ln for ln in source.splitlines() if re.match(rf"\s+(import|from) {package}", ln)]
        assert imports, f"{adapter} no longer imports {package}"
        ignored = [ln.strip() for ln in imports if "type: ignore" in ln]
        assert not ignored, f"{adapter} hides its SDK import from mypy: {ignored}"


def test_both_mypy_configs_excuse_the_sdks_only_while_they_are_not_installed() -> None:
    """The plain install has no SDK, so both configs tell mypy not to report
    the two packages missing. `make lint-providers` reads neither config."""
    text = (REPO_ROOT / "agents" / "pyproject.toml").read_text(encoding="utf-8")
    overrides = tomllib.loads(text)["tool"]["mypy"]["overrides"]
    in_package = {m for o in overrides if o.get("ignore_missing_imports") for m in o["module"]}
    root = configparser.ConfigParser()
    root.read(REPO_ROOT / "mypy.ini", encoding="utf-8")
    in_root = {
        section.removeprefix("mypy-")
        for section in root.sections()
        if section.startswith("mypy-") and root[section].getboolean("ignore_missing_imports")
    }
    for module in ("google.genai", "ibm_watsonx_ai", "ibm_watsonx_ai.*"):
        assert module in in_package, f"agents/pyproject.toml does not excuse {module}"
        assert module in in_root, f"mypy.ini does not excuse {module}"


def test_the_python_job_checks_the_sdks_after_every_check_of_the_plain_install() -> None:
    steps = ci_job_steps("python")
    runs = [str(step.get("run", "")).strip() for step in steps]
    wanted = [f"make {target}" for target in PROVIDER_TARGETS]
    for command in wanted:
        assert runs.count(command) == 1, f"the python job must run `{command}` exactly once"
    install = runs.index(wanted[0])
    # Installing the extra adds packages to the job's one environment. Every
    # step before it saw the plain install; from it on, the job is the four
    # provider steps and nothing else, each a plain `run:`. A `uses:` step
    # would run in the changed environment, and an `if:` or a
    # `continue-on-error:` would let a provider step be skipped or fail
    # without failing the job.
    tail = steps[install:]
    assert [str(step.get("run", "")).strip() for step in tail] == wanted, (
        f"from the SDK install on, the job must be exactly: {wanted}"
    )
    for step in tail:
        assert set(step) == {"name", "run"}, f"{step.get('name')!r} has more than a name and a run"


def _refresh_steps() -> dict[str, str]:
    doc = yaml.safe_load(
        (GITHUB / "workflows" / "python-constraints-refresh.yml").read_text(encoding="utf-8")
    )
    return {s["id"]: str(s.get("run", "")) for s in doc["jobs"]["refresh"]["steps"] if "id" in s}


def _refresh_targets() -> list[str]:
    """The Make targets the refresh's check loop runs, in order."""
    script = " ".join(_refresh_steps()["checks"].replace("\\\n", " ").split())
    listed = re.search(r"for target in (.+?); do", script)
    assert listed, "the refresh's checks step has no `for target in …; do` loop"
    return shlex.split(listed.group(1))


def test_the_weekly_refresh_moves_tries_and_commits_both_files() -> None:
    steps = _refresh_steps()
    for step in ("resolve", "push"):
        for path in (BASE_ARG, PROVIDERS_ARG):
            assert path in steps[step], f"the refresh's `{step}` step leaves out {path}"
    targets = _refresh_targets()
    tail = len(PROVIDER_TARGETS)
    assert targets[-tail:] == list(PROVIDER_TARGETS), (
        f"the refresh must end with the provider targets, in order: {targets}"
    )
    plain = targets[:-tail]
    # The plain install is tried first and whole, its own license check
    # included; no provider target may run before the SDKs are installed.
    assert "test-python" in plain and "check-licenses-python" in plain, plain
    assert not set(plain) & set(PROVIDER_TARGETS), plain
